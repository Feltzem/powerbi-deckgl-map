// Bundles src/workers/geometryDecoder.worker.ts into src/geometryWorkerSource.ts as a string. Power BI visuals
// ship as one bundle and can't load a worker file by URL, so the visual starts the worker from a Blob URL.
//   node scripts/generate-geometry-worker.cjs           write the file if it changed
//   node scripts/generate-geometry-worker.cjs --check   fail if the committed file is stale
const fs = require("node:fs");
const path = require("node:path");
const esbuild = require("esbuild");

const workspaceRoot = path.resolve(__dirname, "..");
const entryPath = path.join(workspaceRoot, "src", "workers", "geometryDecoder.worker.ts");
const outputPath = path.join(workspaceRoot, "src", "geometryWorkerSource.ts");

function buildWorkerModuleSource() {
  const result = esbuild.buildSync({
    entryPoints: [entryPath],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: "es2020",
    minify: true,
    legalComments: "none",
    // The Emscripten loader reads import.meta.url to locate wkp_core.wasm. The worker always passes the Wasm
    // bytes in, so any absolute URL works here.
    define: { "import.meta.url": '"https://localhost/"' },
    logLevel: "silent",
  });
  const code = result.outputFiles[0].text.trim();
  return [
    "// Generated by scripts/generate-geometry-worker.cjs from src/workers/geometryDecoder.worker.ts. Do not edit.",
    `export const GEOMETRY_WORKER_SOURCE = ${JSON.stringify(code)};`,
    "",
  ].join("\n");
}

module.exports = { buildWorkerModuleSource, outputPath };

if (require.main === module) {
  const content = buildWorkerModuleSource();
  const existing = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : null;
  const relative = path.relative(workspaceRoot, outputPath);
  if (process.argv.includes("--check")) {
    if (existing !== content) {
      console.error(`${relative} is stale. Run npm run generate:geometry-worker.`);
      process.exit(1);
    }
    console.log(`${relative} is up to date`);
  } else if (existing === content) {
    console.log(`Already up to date ${relative}`);
  } else {
    fs.writeFileSync(outputPath, content, "utf8");
    console.log(`Generated ${relative} (${(content.length / 1024).toFixed(0)} KB)`);
  }
}
